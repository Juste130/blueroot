// Generates src/lib/chain/abi.ts from the Foundry build output, so the app always uses the ABIs
// of the audited contracts. Run after `forge build`: `npm run app abi`.
import { readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../contracts/out/", import.meta.url);
const TARGET = new URL("../src/lib/chain/abi.ts", import.meta.url);
const CONTRACTS = ["ProjectRegistry", "Verification", "CarbonCredit", "Marketplace", "MockUSDC"];

let source = "// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n";
for (const name of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(new URL(`${name}.sol/${name}.json`, OUT), "utf8"));
  const symbol = `${name[0].toLowerCase()}${name.slice(1)}Abi`.replace("mockUSDCAbi", "paymentTokenAbi");
  source += `\nexport const ${symbol} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(TARGET, source);
console.log(`wrote ${TARGET.pathname} (${CONTRACTS.length} ABIs)`);
